



 function bitvector_indices_matrix(vecs::Vector{BitVector})
     # Get the column indices where the bit is 1
     idxs = [findall(x -> x == 1, row) for row in vecs]
     # Determine the maximum number of 1s across all rows
     maxlen = maximum(length.(idxs))
     # Pad each row appropriately
     padded = [isempty(r) ? fill(0, maxlen) :
               length(r) == maxlen ? r :
               vcat(r, fill(r[end], maxlen - length(r))) for r in idxs]
     return reduce(vcat, padded')  # Stack transposed row vectors into matrix
 end


function read_data_csv(data_fn; adj_matrix=NaN, max_real_biome=NaN)


    data = readdlm(data_fn, ',', String)
    biomes = unique(data[1,2:end])
    species = data[2:end,1]
    biome_affs_data = data[2:end,2:end]

    if isnan(max_real_biome)
        max_real_biome = length(biomes)
    end

    nbiomes = length(biomes)

    obs_biome_affs = fill(0, length(species), length(biomes)    )
    obs_biome_affs[biome_affs_data.=="1"]  .= 1
    obs_biome_affs[biome_affs_data.=="2"]  .= 2
    obs_biome_affs[biome_affs_data.=="NA"] .= 0
    obs_biome_affs[biome_affs_data.=="NaN"] .= 0

    rf_states = make_rf_states(nbiomes::Int64, max_real_biome)

    obs_tip_states = Vector{Int64}(undef, size(obs_biome_affs, 1))
    missing_state_rows = Int64[]

    for i in axes(obs_biome_affs, 1)
        obs_state = vec(obs_biome_affs[i, :])
        state_ind = findfirst(==(obs_state), rf_states)

        if isnothing(state_ind)
            push!(missing_state_rows, i)
        else
            obs_tip_states[i] = state_ind
        end
    end

    if !isempty(missing_state_rows)
        missing_species = species[missing_state_rows]
        missing_states = [vec(obs_biome_affs[i, :]) for i in missing_state_rows]
        error(
            "Some observed tip states are not present in the RF state space. " *
            "Increase max_real_biome/max_range or fix the affinity table. " *
            "max_real_biome=$(max_real_biome); missing species/states=$(collect(zip(missing_species, missing_states)))"
        )
    end



    forbidden_aff_one_hot = [biome_affs_data[i,:] .== "0" for i in eachindex(species)]
    forbidden_fund = if any(any(row) for row in forbidden_aff_one_hot)
        bitvector_indices_matrix(forbidden_aff_one_hot)
    else
        NaN
    end

    tip_probs = get_emp_tip_probs(rf_states, obs_tip_states, adj_matrix, forbidden_fund)

    return tip_probs, nbiomes, rf_states
end




